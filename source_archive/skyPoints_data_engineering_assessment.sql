    MEMBER_ID,
    ENROLLMENT_DATE,
    LAST_FLIGHT_DATE,
    TIER_CODE,
    AGENT_NAME,
    STATE,
    COUNTRY,
    DOB,
    AGE,
    IS_ACTIVE,
    STALE_MEMBER,
    SOURCE_FILE,
    INGESTION_TIME,
    BATCH_ID,
    POST_CODE
)
VALUES (
    S.MEMBER_NAME,
    S.MEMBER_ID,
    S.ENROLLMENT_DATE,
    S.LAST_FLIGHT_DATE,
    S.TIER_CODE,
    S.AGENT_NAME,
    S.STATE,
    S.COUNTRY,
    S.DOB,
    S.AGE,
    S.IS_ACTIVE,
    S.STALE_MEMBER,
    S.SOURCE_FILE,
    S.INGESTION_TIME,
    S.BATCH_ID,
    S.POST_CODE
);

