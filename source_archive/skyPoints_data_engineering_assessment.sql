CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.AUDIT.DQ_AUDIT_LOG (
    AUDIT_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    BATCH_ID VARCHAR(100),
    TABLE_NAME VARCHAR(255),
    TOTAL_RECORDS NUMBER,
    VALID_RECORDS NUMBER,
    REJECTED_RECORDS NUMBER,
    VALIDATION_STATUS VARCHAR(30),
    EXECUTION_TIME TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    COMMENTS VARCHAR(1000)
);


INSERT INTO SKYPOINTS_DB.AUDIT.DQ_AUDIT_LOG (
    BATCH_ID,
    TABLE_NAME,
    TOTAL_RECORDS,
    VALID_RECORDS,
    REJECTED_RECORDS,
    VALIDATION_STATUS,
    COMMENTS
)
SELECT
    'BATCH_001',
    'STG_MEMBER_PROFILE',
    COUNT(*),
    COUNT_IF(
        MEMBER_ID IS NOT NULL
        AND TRIM(MEMBER_ID) <> ''
        AND MEMBER_NAME IS NOT NULL
        AND TRIM(MEMBER_NAME) <> ''
        AND COUNTRY IN ('IND', 'USA', 'PHIL', 'CAN', 'AU')
        AND ENROLLMENT_DATE IS NOT NULL
        AND ENROLLMENT_DATE <= CURRENT_DATE()
        AND (DOB IS NULL OR (
            DOB <= CURRENT_DATE()
            AND DOB >= DATEADD(YEAR, -120, CURRENT_DATE())
        ))
        AND (IS_ACTIVE IN ('A', 'I'))
        AND (AGE IS NULL OR AGE BETWEEN 0 AND 120)
        AND (LAST_FLIGHT_DATE IS NULL
             OR LAST_FLIGHT_DATE <= CURRENT_DATE())
    ),
    COUNT_IF(
        MEMBER_ID IS NULL
        OR TRIM(MEMBER_ID) = ''
        OR MEMBER_NAME IS NULL
        OR TRIM(MEMBER_NAME) = ''
        OR COUNTRY NOT IN ('IND', 'USA', 'PHIL', 'CAN', 'AU')
        OR COUNTRY IS NULL
        OR ENROLLMENT_DATE IS NULL
        OR ENROLLMENT_DATE > CURRENT_DATE()
        OR (DOB IS NOT NULL AND (
            DOB > CURRENT_DATE()
            OR DOB < DATEADD(YEAR, -120, CURRENT_DATE())
        ))
        OR IS_ACTIVE NOT IN ('A', 'I')
        OR IS_ACTIVE IS NULL
        OR (AGE IS NOT NULL AND (AGE < 0 OR AGE > 120))
        OR LAST_FLIGHT_DATE > CURRENT_DATE()
    ),
    CASE
        WHEN COUNT_IF(
            MEMBER_ID IS NULL
            OR TRIM(MEMBER_ID) = ''
            OR MEMBER_NAME IS NULL
            OR TRIM(MEMBER_NAME) = ''
            OR COUNTRY NOT IN ('IND', 'USA', 'PHIL', 'CAN', 'AU')
            OR COUNTRY IS NULL
            OR ENROLLMENT_DATE IS NULL
            OR ENROLLMENT_DATE > CURRENT_DATE()
            OR (DOB IS NOT NULL AND (
                DOB > CURRENT_DATE()
                OR DOB < DATEADD(YEAR, -120, CURRENT_DATE())
            ))
            OR IS_ACTIVE NOT IN ('A', 'I')
            OR IS_ACTIVE IS NULL
            OR (AGE IS NOT NULL AND (AGE < 0 OR AGE > 120))
            OR LAST_FLIGHT_DATE > CURRENT_DATE()
        ) = 0 THEN 'PASSED'
        ELSE 'FAILED'
    END,
    'Member profile mandatory fields and business-rule validation'
FROM SKYPOINTS_DB.STAGING.STG_MEMBER_PROFILE;


SELECT
    BATCH_ID,
    TABLE_NAME,
    TOTAL_RECORDS,
    VALID_RECORDS,
    REJECTED_RECORDS,
    VALIDATION_STATUS,
    EXECUTION_TIME,
    COMMENTS
FROM SKYPOINTS_DB.AUDIT.DQ_AUDIT_LOG
ORDER BY EXECUTION_TIME DESC;



CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.AUDIT.REJECTED_MEMBER_RECORDS (
    MEMBER_ID VARCHAR(18),
    MEMBER_NAME VARCHAR(255),
    COUNTRY VARCHAR(5),
    BATCH_ID VARCHAR(100),
    SOURCE_FILE VARCHAR(500),
    REJECTION_REASON VARCHAR(1000),
    REJECTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


INSERT INTO SKYPOINTS_DB.AUDIT.REJECTED_MEMBER_RECORDS (
    MEMBER_ID,
    MEMBER_NAME,
    COUNTRY,
    BATCH_ID,
    SOURCE_FILE,
    REJECTION_REASON
)
SELECT
    MEMBER_ID,
    MEMBER_NAME,
    COUNTRY,
    BATCH_ID,
    SOURCE_FILE,
    CONCAT_WS(', ',
        IFF(MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '',
             'MISSING_MEMBER_ID', NULL),
        IFF(MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = '',
             'MISSING_MEMBER_NAME', NULL),
        IFF(COUNTRY IS NULL OR COUNTRY NOT IN ('IND','USA','PHIL','CAN','AU'),
             'INVALID_COUNTRY', NULL),
        IFF(ENROLLMENT_DATE IS NULL OR ENROLLMENT_DATE > CURRENT_DATE(),
             'INVALID_ENROLLMENT_DATE', NULL),
        IFF(IS_ACTIVE IS NULL OR IS_ACTIVE NOT IN ('A','I'),
             'INVALID_ACTIVE_FLAG', NULL),
        IFF(AGE IS NOT NULL AND (AGE < 0 OR AGE > 120),
             'INVALID_AGE', NULL),
        IFF(LAST_FLIGHT_DATE > CURRENT_DATE(),
             'FUTURE_FLIGHT_DATE', NULL)
    ) AS REJECTION_REASON
FROM SKYPOINTS_DB.STAGING.STG_MEMBER_PROFILE
WHERE
       MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = ''
    OR MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = ''
    OR COUNTRY IS NULL OR COUNTRY NOT IN ('IND','USA','PHIL','CAN','AU')
    OR ENROLLMENT_DATE IS NULL OR ENROLLMENT_DATE > CURRENT_DATE()
    OR IS_ACTIVE IS NULL OR IS_ACTIVE NOT IN ('A','I')
    OR (AGE IS NOT NULL AND (AGE < 0 OR AGE > 120))
    OR LAST_FLIGHT_DATE > CURRENT_DATE();



