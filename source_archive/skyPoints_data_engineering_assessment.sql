    T.MEMBER_NAME IS DISTINCT FROM S.MEMBER_NAME OR
    T.ENROLLMENT_DATE IS DISTINCT FROM S.ENROLLMENT_DATE OR
    T.LAST_FLIGHT_DATE IS DISTINCT FROM S.LAST_FLIGHT_DATE OR
