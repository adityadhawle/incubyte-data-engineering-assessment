    S.LAST_FLIGHT_DATE, S.TIER_CODE, S.AGENT_NAME,
    S.STATE, S.COUNTRY, S.DOB, S.IS_ACTIVE,
    'member_profile_sample.txt', CURRENT_TIMESTAMP(),
    'FILE_BATCH_001'
);

