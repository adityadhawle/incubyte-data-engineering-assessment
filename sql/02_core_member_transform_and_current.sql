SELECT
    MEMBER_NAME,
    MEMBER_ID,
    TRY_TO_DATE(ENROLLMENT_DATE, 'YYYYMMDD'),
    TRY_TO_DATE(LAST_FLIGHT_DATE, 'YYYYMMDD'),
    TIER_CODE,
    AGENT_NAME,
    STATE,
    COUNTRY,
    TRY_TO_DATE(DOB, 'MMDDYYYY'),

    CASE
        WHEN TRY_TO_DATE(DOB, 'MMDDYYYY') IS NOT NULL
        THEN
            DATEDIFF(YEAR, TRY_TO_DATE(DOB, 'MMDDYYYY'), CURRENT_DATE())
            - IFF(
                TO_CHAR(CURRENT_DATE(), 'MMDD')
                < TO_CHAR(TRY_TO_DATE(DOB, 'MMDDYYYY'), 'MMDD'),
                1, 0
            )
        ELSE NULL
    END,

    IS_ACTIVE,

    CASE
        WHEN TRY_TO_DATE(LAST_FLIGHT_DATE, 'YYYYMMDD') IS NULL
            THEN NULL
        WHEN DATEDIFF(
            DAY,
            TRY_TO_DATE(LAST_FLIGHT_DATE, 'YYYYMMDD'),
            CURRENT_DATE()
        ) > 90
            THEN TRUE
        ELSE FALSE
    END,

    SOURCE_FILE,
    INGESTION_TIME,
    BATCH_ID

FROM SKYPOINTS_DB.RAW.RAW_MEMBER_PROFILE;


SELECT
    MEMBER_NAME,
    MEMBER_ID,
