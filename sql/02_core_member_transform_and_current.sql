INSERT INTO SKYPOINTS_DB.STAGING.STG_MEMBER_PROFILE
(
    MEMBER_NAME,
    MEMBER_ID,
    ENROLLMENT_DATE,
    LAST_FLIGHT_DATE,
    TIER_CODE,
    AGENT_NAME,
    STATE,
    COUNTRY,
    DOB,
    AGE,
    IS_ACTIVE,
    STALE_MEMBER,
    SOURCE_FILE,
    INGESTION_TIME,
