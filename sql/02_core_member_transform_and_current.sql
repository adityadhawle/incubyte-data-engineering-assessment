MERGE INTO SKYPOINTS_DB.TARGET.MEMBER_CURRENT T
USING (
    SELECT *
    FROM SKYPOINTS_DB.STAGING.STG_MEMBER_PROFILE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID
        ORDER BY INGESTION_TIME DESC, BATCH_ID DESC
    ) = 1
) S
ON T.MEMBER_ID = S.MEMBER_ID

WHEN MATCHED AND S.INGESTION_TIME > T.INGESTION_TIME
THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.COUNTRY = S.COUNTRY,
    T.STATE = S.STATE,
    T.INGESTION_TIME = S.INGESTION_TIME,
    T.BATCH_ID = S.BATCH_ID

WHEN NOT MATCHED
THEN INSERT (
    MEMBER_NAME, MEMBER_ID, ENROLLMENT_DATE,
    LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME,
    STATE, COUNTRY, DOB, AGE, IS_ACTIVE,
    STALE_MEMBER, SOURCE_FILE, INGESTION_TIME, BATCH_ID
)
VALUES (
    S.MEMBER_NAME, S.MEMBER_ID, S.ENROLLMENT_DATE,
    S.LAST_FLIGHT_DATE, S.TIER_CODE, S.AGENT_NAME,
    S.STATE, S.COUNTRY, S.DOB, S.AGE, S.IS_ACTIVE,
    S.STALE_MEMBER, S.SOURCE_FILE, S.INGESTION_TIME, S.BATCH_ID
);

