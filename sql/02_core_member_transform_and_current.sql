SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = '')
        AS MISSING_MEMBER_NAME,

    COUNT_IF(MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '')
        AS MISSING_MEMBER_ID,

    COUNT_IF(ENROLLMENT_DATE IS NULL)
        AS INVALID_ENROLLMENT_DATE,

    COUNT_IF(COUNTRY IS NULL OR TRIM(COUNTRY) = '')
        AS MISSING_COUNTRY,

    COUNT_IF(DOB IS NULL)
        AS INVALID_DOB

FROM SKYPOINTS_DB.STAGING.STG_MEMBER_PROFILE;


SELECT
    MEMBER_ID,
    COUNT(*) AS RECORD_COUNT
FROM SKYPOINTS_DB.STAGING.STG_MEMBER_PROFILE
GROUP BY MEMBER_ID
HAVING COUNT(*) > 1;


SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = '')
        AS MISSING_MEMBER_NAME,

    COUNT_IF(MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '')
        AS MISSING_MEMBER_ID,

    COUNT_IF(ENROLLMENT_DATE IS NULL)
        AS INVALID_ENROLLMENT_DATE,

    COUNT_IF(COUNTRY IS NULL OR TRIM(COUNTRY) = '')
        AS MISSING_COUNTRY,

    COUNT_IF(DOB IS NULL)
        AS INVALID_DOB,

    COUNT(DISTINCT MEMBER_ID) AS UNIQUE_MEMBER_IDS

FROM SKYPOINTS_DB.STAGING.STG_MEMBER_PROFILE;




