-- ============================================================
-- 22. TARGET DUPLICATE CHECK
-- Expected result: zero rows.
-- ============================================================

SELECT
    COUNTRY,
    MEMBER_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM (
    SELECT COUNTRY, MEMBER_ID
    FROM SKYPOINTS_DB.TARGET.MEMBER_USA

    UNION ALL

    SELECT COUNTRY, MEMBER_ID
    FROM SKYPOINTS_DB.TARGET.MEMBER_INDIA

    UNION ALL

    SELECT COUNTRY, MEMBER_ID
    FROM SKYPOINTS_DB.TARGET.MEMBER_AUSTRALIA
)
GROUP BY COUNTRY, MEMBER_ID
HAVING COUNT(*) > 1;


-- ============================================================
-- 23. TARGET MANDATORY FIELD CHECK
-- Expected result: zero rows.
-- ============================================================

SELECT
    COUNTRY,
    MEMBER_ID,
    MEMBER_NAME,
    TIER_CODE,
    ENROLLMENT_DATE
FROM (
    SELECT * FROM SKYPOINTS_DB.TARGET.MEMBER_USA

    UNION ALL

    SELECT * FROM SKYPOINTS_DB.TARGET.MEMBER_INDIA

    UNION ALL

    SELECT * FROM SKYPOINTS_DB.TARGET.MEMBER_AUSTRALIA
)
WHERE MEMBER_ID IS NULL
   OR TRIM(MEMBER_ID) = ''
   OR MEMBER_NAME IS NULL
   OR TRIM(MEMBER_NAME) = ''
   OR COUNTRY IS NULL
   OR TIER_CODE IS NULL
   OR ENROLLMENT_DATE IS NULL;


-- ============================================================
-- 24. COUNTRY-WISE DQ SUMMARY
-- ============================================================

SELECT
    COUNTRY,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT MEMBER_ID) AS UNIQUE_MEMBERS,
    COUNT_IF(DQ_STATUS = 'VALID') AS VALID_RECORDS,
    COUNT_IF(DQ_STATUS = 'WARNING') AS WARNING_RECORDS
FROM (
    SELECT COUNTRY, MEMBER_ID, DQ_STATUS
    FROM SKYPOINTS_DB.TARGET.MEMBER_USA

    UNION ALL

    SELECT COUNTRY, MEMBER_ID, DQ_STATUS
    FROM SKYPOINTS_DB.TARGET.MEMBER_INDIA

    UNION ALL

    SELECT COUNTRY, MEMBER_ID, DQ_STATUS
    FROM SKYPOINTS_DB.TARGET.MEMBER_AUSTRALIA
)
GROUP BY COUNTRY
ORDER BY COUNTRY;


