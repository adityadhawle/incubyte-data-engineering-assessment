-- ============================================================
-- 17. USA TARGET MERGE
-- Only valid records are loaded.
-- ============================================================

MERGE INTO SKYPOINTS_DB.TARGET.MEMBER_USA T

USING (
    SELECT *
    FROM COUNTRY_MEMBER_DQ
    WHERE COUNTRY = 'USA'
      AND DQ_STATUS = 'VALID'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID
        ORDER BY INGESTION_TIME DESC NULLS LAST, BATCH_ID DESC
    ) = 1
) S

ON T.MEMBER_ID = S.MEMBER_ID

WHEN MATCHED AND (
       S.INGESTION_TIME > T.INGESTION_TIME
    OR (
        EQUAL_NULL(S.INGESTION_TIME, T.INGESTION_TIME)
        AND S.BATCH_ID > T.BATCH_ID
    )
)
THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.COUNTRY = 'USA',
    T.TIER_CODE = S.TIER_CODE,
    T.DOB = S.DOB,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.FLIGHT_DATE = S.FLIGHT_DATE,
    T.AGE = S.AGE,
    T.STALE_MEMBER = S.STALE_MEMBER,
    T.MEMBER_TYPE = S.MEMBER_TYPE,
    T.DQ_STATUS = S.DQ_STATUS,
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.INGESTION_TIME = S.INGESTION_TIME,
    T.BATCH_ID = S.BATCH_ID

WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, MEMBER_NAME, COUNTRY, TIER_CODE, DOB,
    ENROLLMENT_DATE, FLIGHT_DATE, AGE, STALE_MEMBER,
    MEMBER_TYPE, DQ_STATUS, SOURCE_FILE, INGESTION_TIME, BATCH_ID
)
VALUES (
    S.MEMBER_ID, S.MEMBER_NAME, 'USA', S.TIER_CODE, S.DOB,
    S.ENROLLMENT_DATE, S.FLIGHT_DATE, S.AGE, S.STALE_MEMBER,
    S.MEMBER_TYPE, S.DQ_STATUS, S.SOURCE_FILE, S.INGESTION_TIME, S.BATCH_ID
);


-- ============================================================
-- 18. INDIA TARGET MERGE
-- ============================================================

MERGE INTO SKYPOINTS_DB.TARGET.MEMBER_INDIA T

USING (
    SELECT *
    FROM COUNTRY_MEMBER_DQ
    WHERE COUNTRY = 'INDIA'
      AND DQ_STATUS = 'VALID'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID
        ORDER BY INGESTION_TIME DESC NULLS LAST, BATCH_ID DESC
    ) = 1
) S

ON T.MEMBER_ID = S.MEMBER_ID

WHEN MATCHED AND (
       S.INGESTION_TIME > T.INGESTION_TIME
    OR (
        EQUAL_NULL(S.INGESTION_TIME, T.INGESTION_TIME)
        AND S.BATCH_ID > T.BATCH_ID
    )
)
THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.COUNTRY = 'INDIA',
    T.TIER_CODE = S.TIER_CODE,
    T.DOB = S.DOB,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.FLIGHT_DATE = S.FLIGHT_DATE,
    T.AGE = S.AGE,
    T.STALE_MEMBER = S.STALE_MEMBER,
    T.MEMBER_TYPE = S.MEMBER_TYPE,
    T.DQ_STATUS = S.DQ_STATUS,
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.INGESTION_TIME = S.INGESTION_TIME,
    T.BATCH_ID = S.BATCH_ID

WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, MEMBER_NAME, COUNTRY, TIER_CODE, DOB,
    ENROLLMENT_DATE, FLIGHT_DATE, AGE, STALE_MEMBER,
    MEMBER_TYPE, DQ_STATUS, SOURCE_FILE, INGESTION_TIME, BATCH_ID
)
VALUES (
    S.MEMBER_ID, S.MEMBER_NAME, 'INDIA', S.TIER_CODE, S.DOB,
    S.ENROLLMENT_DATE, S.FLIGHT_DATE, S.AGE, S.STALE_MEMBER,
    S.MEMBER_TYPE, S.DQ_STATUS, S.SOURCE_FILE, S.INGESTION_TIME, S.BATCH_ID
);


-- ============================================================
-- 19. AUSTRALIA TARGET MERGE
-- WARNING records are accepted.
-- Missing enrollment date records are rejected.
-- ============================================================

MERGE INTO SKYPOINTS_DB.TARGET.MEMBER_AUSTRALIA T

USING (
    SELECT *
    FROM COUNTRY_MEMBER_DQ
    WHERE COUNTRY = 'AUSTRALIA'
      AND DQ_STATUS IN ('VALID', 'WARNING')
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID
        ORDER BY INGESTION_TIME DESC NULLS LAST, BATCH_ID DESC
    ) = 1
) S

ON T.MEMBER_ID = S.MEMBER_ID

WHEN MATCHED AND (
       S.INGESTION_TIME > T.INGESTION_TIME
    OR (
        EQUAL_NULL(S.INGESTION_TIME, T.INGESTION_TIME)
        AND S.BATCH_ID > T.BATCH_ID
    )
)
THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.COUNTRY = 'AUSTRALIA',
    T.TIER_CODE = S.TIER_CODE,
    T.DOB = S.DOB,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.FLIGHT_DATE = S.FLIGHT_DATE,
    T.AGE = S.AGE,
    T.STALE_MEMBER = S.STALE_MEMBER,
    T.MEMBER_TYPE = S.MEMBER_TYPE,
    T.DQ_STATUS = S.DQ_STATUS,
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.INGESTION_TIME = S.INGESTION_TIME,
    T.BATCH_ID = S.BATCH_ID

WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, MEMBER_NAME, COUNTRY, TIER_CODE, DOB,
    ENROLLMENT_DATE, FLIGHT_DATE, AGE, STALE_MEMBER,
    MEMBER_TYPE, DQ_STATUS, SOURCE_FILE, INGESTION_TIME, BATCH_ID
)
VALUES (
    S.MEMBER_ID, S.MEMBER_NAME, 'AUSTRALIA', S.TIER_CODE, S.DOB,
    S.ENROLLMENT_DATE, S.FLIGHT_DATE, S.AGE, S.STALE_MEMBER,
    S.MEMBER_TYPE, S.DQ_STATUS, S.SOURCE_FILE, S.INGESTION_TIME, S.BATCH_ID
);


