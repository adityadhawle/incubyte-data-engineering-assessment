WITH ALL_COUNTRY_DATA AS (

    SELECT
        MEMBER_ID,
        MEMBER_NAME,
        'USA' AS COUNTRY,
        TIER_CODE,
        ENROLLMENT_DATE,
        FLIGHT_DATE,
        NULL::DATE AS DOB,
        'USA' AS SOURCE
    FROM SKYPOINTS_DB.STAGING.STG_USA_MEMBERS

    UNION ALL

    SELECT
        MEMBER_ID,
        MEMBER_NAME,
        'INDIA',
        TIER_CODE,
        ENROLLMENT_DATE,
        FLIGHT_DATE,
        DOB,
        'INDIA'
    FROM SKYPOINTS_DB.STAGING.STG_INDIA_MEMBERS

    UNION ALL

    SELECT
        MEMBER_ID,
        MEMBER_NAME,
        'AUSTRALIA',
        TIER_CODE,
        ENROLLMENT_DATE,
        FLIGHT_DATE,
        DOB,
        'AUSTRALIA'
    FROM SKYPOINTS_DB.STAGING.STG_AUS_MEMBERS
),

DQ_RESULTS AS (
    SELECT
        *,
        ARRAY_TO_STRING(
            ARRAY_CONSTRUCT_COMPACT(
                IFF(MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '',
                    'Missing Member ID', NULL),
                IFF(MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = '',
                    'Missing Member Name', NULL),
                IFF(TIER_CODE IS NULL OR TRIM(TIER_CODE) = '',
                    'Missing Tier Code', NULL),
                IFF(ENROLLMENT_DATE IS NULL,
                    'Invalid or Missing Enrollment Date', NULL),
                IFF(FLIGHT_DATE IS NULL,
                    'Invalid or Missing Flight Date', NULL)
            ),
            '; '
        ) AS REJECTION_REASON,

        IFF(COUNTRY = 'AUSTRALIA' AND DOB IS NULL,
            'DOB missing in source', NULL) AS WARNING_REASON

    FROM ALL_COUNTRY_DATA
)

SELECT
    MEMBER_ID,
    MEMBER_NAME,
    COUNTRY,
    SOURCE,
    REJECTION_REASON,
    WARNING_REASON,
    CASE
        WHEN REJECTION_REASON <> '' THEN 'REJECT'
        WHEN WARNING_REASON IS NOT NULL THEN 'WARNING'
        ELSE 'VALID'
    END AS DQ_STATUS
FROM DQ_RESULTS
ORDER BY COUNTRY, MEMBER_ID;


WITH ALL_IDS AS (
    SELECT MEMBER_ID, 'USA' AS COUNTRY
    FROM SKYPOINTS_DB.STAGING.STG_USA_MEMBERS

