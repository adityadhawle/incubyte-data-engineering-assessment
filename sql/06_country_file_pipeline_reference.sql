SELECT
    COUNTRY,
    MEMBER_ID,
    MEMBER_NAME,
    TIER_CODE,
    ENROLLMENT_DATE
FROM (
    SELECT * FROM SKYPOINTS_DB.TARGET.MEMBER_USA
    UNION ALL
    SELECT * FROM SKYPOINTS_DB.TARGET.MEMBER_INDIA
    UNION ALL
    SELECT * FROM SKYPOINTS_DB.TARGET.MEMBER_AUSTRALIA
)
WHERE MEMBER_ID IS NULL
   OR TRIM(MEMBER_ID) = ''
   OR MEMBER_NAME IS NULL
   OR TRIM(MEMBER_NAME) = ''
   OR COUNTRY IS NULL
   OR TIER_CODE IS NULL
   OR ENROLLMENT_DATE IS NULL;

   MERGE INTO SKYPOINTS_DB.TARGET.MEMBER_USA T
USING (
    SELECT *
    FROM SKYPOINTS_DB.STAGING.STG_USA_MEMBERS
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID
        ORDER BY INGESTION_TIME DESC, BATCH_ID DESC
    ) = 1
) S
ON T.MEMBER_ID = S.MEMBER_ID

WHEN MATCHED
 AND S.INGESTION_TIME >= T.INGESTION_TIME
THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.TIER_CODE = S.TIER_CODE,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.FLIGHT_DATE = S.FLIGHT_DATE,
    T.AGE = S.AGE,
    T.STALE_MEMBER = S.STALE_MEMBER,
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.INGESTION_TIME = S.INGESTION_TIME,
    T.BATCH_ID = S.BATCH_ID

WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, MEMBER_NAME, COUNTRY, TIER_CODE, DOB,
    ENROLLMENT_DATE, FLIGHT_DATE, AGE, STALE_MEMBER,
    MEMBER_TYPE, DQ_STATUS, SOURCE_FILE, INGESTION_TIME, BATCH_ID
)
VALUES (
    S.MEMBER_ID, S.MEMBER_NAME, 'USA', S.TIER_CODE, NULL,
    S.ENROLLMENT_DATE, S.FLIGHT_DATE, S.AGE, S.STALE_MEMBER,
    NULL, 'VALID', S.SOURCE_FILE, S.INGESTION_TIME, S.BATCH_ID
);

MERGE INTO SKYPOINTS_DB.TARGET.MEMBER_INDIA T
USING (
    SELECT *
    FROM SKYPOINTS_DB.STAGING.STG_INDIA_MEMBERS
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID
        ORDER BY INGESTION_TIME DESC, BATCH_ID DESC
    ) = 1
) S
ON T.MEMBER_ID = S.MEMBER_ID

WHEN MATCHED
 AND S.INGESTION_TIME >= T.INGESTION_TIME
THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.TIER_CODE = S.TIER_CODE,
    T.DOB = S.DOB,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.FLIGHT_DATE = S.FLIGHT_DATE,
    T.AGE = S.AGE,
    T.STALE_MEMBER = S.STALE_MEMBER,
    T.MEMBER_TYPE = S.MEMBER_TYPE,
    T.DQ_STATUS = 'VALID',
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.INGESTION_TIME = S.INGESTION_TIME,
    T.BATCH_ID = S.BATCH_ID

WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, MEMBER_NAME, COUNTRY, TIER_CODE, DOB,
    ENROLLMENT_DATE, FLIGHT_DATE, AGE, STALE_MEMBER,
    MEMBER_TYPE, DQ_STATUS, SOURCE_FILE, INGESTION_TIME, BATCH_ID
)
VALUES (
    S.MEMBER_ID, S.MEMBER_NAME, 'INDIA', S.TIER_CODE, S.DOB,
    S.ENROLLMENT_DATE, S.FLIGHT_DATE, S.AGE, S.STALE_MEMBER,
    S.MEMBER_TYPE, 'VALID', S.SOURCE_FILE, S.INGESTION_TIME, S.BATCH_ID
);

MERGE INTO SKYPOINTS_DB.TARGET.MEMBER_AUSTRALIA T
USING (
    SELECT *
    FROM SKYPOINTS_DB.STAGING.STG_AUS_MEMBERS
    WHERE ENROLLMENT_DATE IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID
        ORDER BY INGESTION_TIME DESC, BATCH_ID DESC
    ) = 1
) S
ON T.MEMBER_ID = S.MEMBER_ID

WHEN MATCHED
 AND S.INGESTION_TIME >= T.INGESTION_TIME
THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.TIER_CODE = S.TIER_CODE,
    T.DOB = S.DOB,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.FLIGHT_DATE = S.FLIGHT_DATE,
    T.AGE = S.AGE,
    T.STALE_MEMBER = S.STALE_MEMBER,
    T.DQ_STATUS = CASE
        WHEN S.DOB IS NULL THEN 'WARNING'
        ELSE 'VALID'
    END,
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.INGESTION_TIME = S.INGESTION_TIME,
    T.BATCH_ID = S.BATCH_ID

WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, MEMBER_NAME, COUNTRY, TIER_CODE, DOB,
    ENROLLMENT_DATE, FLIGHT_DATE, AGE, STALE_MEMBER,
    MEMBER_TYPE, DQ_STATUS, SOURCE_FILE, INGESTION_TIME, BATCH_ID
)
VALUES (
    S.MEMBER_ID, S.MEMBER_NAME, 'AUSTRALIA', S.TIER_CODE, S.DOB,
    S.ENROLLMENT_DATE, S.FLIGHT_DATE, S.AGE, S.STALE_MEMBER,
    NULL,
    CASE WHEN S.DOB IS NULL THEN 'WARNING' ELSE 'VALID' END,
    S.SOURCE_FILE, S.INGESTION_TIME, S.BATCH_ID
);


SELECT
    COUNTRY,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT MEMBER_ID) AS UNIQUE_MEMBERS,
    COUNT_IF(DQ_STATUS = 'VALID') AS VALID_RECORDS,
    COUNT_IF(DQ_STATUS = 'WARNING') AS WARNING_RECORDS
FROM (
    SELECT COUNTRY, MEMBER_ID, DQ_STATUS
    FROM SKYPOINTS_DB.TARGET.MEMBER_USA

    UNION ALL

    SELECT COUNTRY, MEMBER_ID, DQ_STATUS
    FROM SKYPOINTS_DB.TARGET.MEMBER_INDIA

    UNION ALL

    SELECT COUNTRY, MEMBER_ID, DQ_STATUS
    FROM SKYPOINTS_DB.TARGET.MEMBER_AUSTRALIA
)
GROUP BY COUNTRY
ORDER BY COUNTRY;

