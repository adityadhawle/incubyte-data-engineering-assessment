INSERT INTO SKYPOINTS_DB.AUDIT.DQ_AUDIT_LOG
(
    BATCH_ID,
    TABLE_NAME,
    TOTAL_RECORDS,
    VALID_RECORDS,
    REJECTED_RECORDS,
    VALIDATION_STATUS,
    COMMENTS
)
SELECT
    'BATCH_COUNTRY_001',
    'COUNTRY_STAGING_ALL',
    COUNT(*),
    COUNT_IF(DQ_STATUS IN ('VALID', 'WARNING')),
    COUNT_IF(DQ_STATUS = 'REJECT'),

    CASE
        WHEN COUNT_IF(DQ_STATUS = 'REJECT') = 0
            THEN 'PASSED'
        ELSE 'COMPLETED_WITH_REJECTIONS'
    END,

    'Country staging DQ: warnings are accepted; rejected records are quarantined.'

FROM COUNTRY_MEMBER_DQ

WHERE NOT EXISTS (
    SELECT 1
    FROM SKYPOINTS_DB.AUDIT.DQ_AUDIT_LOG A
    WHERE A.BATCH_ID = 'BATCH_COUNTRY_001'
      AND A.TABLE_NAME = 'COUNTRY_STAGING_ALL'
);


