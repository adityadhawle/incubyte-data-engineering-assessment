-- ============================================================
-- 9. COMBINE ALL COUNTRY RECORDS
-- ============================================================

CREATE OR REPLACE TEMPORARY VIEW COUNTRY_MEMBER_DQ AS

WITH ALL_COUNTRY_DATA AS (

    SELECT
        MEMBER_ID,
        MEMBER_NAME,
        'USA' AS COUNTRY,
        TIER_CODE,
        ENROLLMENT_DATE,
        FLIGHT_DATE,
        NULL::DATE AS DOB,
        AGE,
        STALE_MEMBER,
        CAST(NULL AS VARCHAR(50)) AS MEMBER_TYPE,
        SOURCE_FILE,
        INGESTION_TIME,
        BATCH_ID
    FROM SKYPOINTS_DB.STAGING.STG_USA_MEMBERS

    UNION ALL

    SELECT
        MEMBER_ID,
        MEMBER_NAME,
        'INDIA',
        TIER_CODE,
        ENROLLMENT_DATE,
        FLIGHT_DATE,
        DOB,
        AGE,
        STALE_MEMBER,
        MEMBER_TYPE,
        SOURCE_FILE,
        INGESTION_TIME,
        BATCH_ID
    FROM SKYPOINTS_DB.STAGING.STG_INDIA_MEMBERS

    UNION ALL

    SELECT
        MEMBER_ID,
        MEMBER_NAME,
        'AUSTRALIA',
        TIER_CODE,
        ENROLLMENT_DATE,
        FLIGHT_DATE,
        DOB,
        AGE,
        STALE_MEMBER,
        CAST(NULL AS VARCHAR(50)),
        SOURCE_FILE,
        INGESTION_TIME,
        BATCH_ID
    FROM SKYPOINTS_DB.STAGING.STG_AUS_MEMBERS
)

SELECT
    A.*,

    ARRAY_TO_STRING(
        ARRAY_CONSTRUCT_COMPACT(
            IFF(
                MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '',
                'MISSING_MEMBER_ID', NULL
            ),
            IFF(
                MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = '',
                'MISSING_MEMBER_NAME', NULL
            ),
            IFF(
                TIER_CODE IS NULL OR TRIM(TIER_CODE) = '',
                'MISSING_TIER_CODE', NULL
            ),
            IFF(
                ENROLLMENT_DATE IS NULL,
                'INVALID_OR_MISSING_ENROLLMENT_DATE', NULL
            ),
            IFF(
                FLIGHT_DATE IS NULL,
                'INVALID_OR_MISSING_FLIGHT_DATE', NULL
            ),
            IFF(
                DOB > CURRENT_DATE()
                OR DOB < DATEADD(YEAR, -120, CURRENT_DATE()),
                'INVALID_DOB', NULL
            ),
            IFF(
                AGE < 0 OR AGE > 120,
                'INVALID_AGE', NULL
            )
        ),
        '; '
    ) AS REJECTION_REASON,

    IFF(
        COUNTRY = 'AUSTRALIA' AND DOB IS NULL,
        'DOB_MISSING_IN_SOURCE',
        NULL
    ) AS WARNING_REASON,

    CASE
        WHEN MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = ''
          OR MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = ''
          OR TIER_CODE IS NULL OR TRIM(TIER_CODE) = ''
          OR ENROLLMENT_DATE IS NULL
          OR FLIGHT_DATE IS NULL
          OR DOB > CURRENT_DATE()
          OR DOB < DATEADD(YEAR, -120, CURRENT_DATE())
          OR AGE < 0 OR AGE > 120
            THEN 'REJECT'

        WHEN COUNTRY = 'AUSTRALIA' AND DOB IS NULL
            THEN 'WARNING'

        ELSE 'VALID'
    END AS DQ_STATUS

FROM ALL_COUNTRY_DATA A;


