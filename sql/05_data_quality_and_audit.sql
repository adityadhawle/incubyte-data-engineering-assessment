SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '')
        AS MISSING_MEMBER_ID,

    COUNT_IF(MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = '')
        AS MISSING_MEMBER_NAME,

    COUNT_IF(COUNTRY IS NULL OR TRIM(COUNTRY) = '')
        AS MISSING_COUNTRY,

    COUNT_IF(LENGTH(MEMBER_ID) > 18)
        AS MEMBER_ID_TOO_LONG,

    COUNT_IF(IS_ACTIVE NOT IN ('A', 'I') OR IS_ACTIVE IS NULL)
        AS INVALID_ACTIVE_FLAG,

    COUNT_IF(AGE < 0 OR AGE > 120)
        AS INVALID_AGE,

    COUNT_IF(LAST_FLIGHT_DATE > CURRENT_DATE())
        AS FUTURE_FLIGHT_DATE

FROM SKYPOINTS_DB.STAGING.STG_MEMBER_PROFILE;


SELECT
    MEMBER_ID,
    MEMBER_NAME,
    COUNTRY,
    ENROLLMENT_DATE,
    DOB,
    CASE
        WHEN COUNTRY NOT IN ('IND', 'USA', 'PHIL', 'CAN', 'AU')
            THEN 'INVALID_COUNTRY'
        WHEN ENROLLMENT_DATE IS NULL
            THEN 'MISSING_ENROLLMENT_DATE'
        WHEN ENROLLMENT_DATE > CURRENT_DATE()
            THEN 'FUTURE_ENROLLMENT_DATE'
        WHEN DOB > CURRENT_DATE()
            THEN 'FUTURE_DOB'
        WHEN DOB < DATEADD(YEAR, -120, CURRENT_DATE())
            THEN 'DOB_OVER_120_YEARS'
        ELSE 'VALID'
    END AS VALIDATION_STATUS
FROM SKYPOINTS_DB.STAGING.STG_MEMBER_PROFILE
WHERE
       COUNTRY IS NULL
    OR COUNTRY NOT IN ('IND', 'USA', 'PHIL', 'CAN', 'AU')
    OR ENROLLMENT_DATE IS NULL
    OR ENROLLMENT_DATE > CURRENT_DATE()
    OR DOB > CURRENT_DATE()
    OR DOB < DATEADD(YEAR, -120, CURRENT_DATE());

