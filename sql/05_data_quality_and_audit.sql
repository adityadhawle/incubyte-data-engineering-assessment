SELECT
    COUNT(*) AS TOTAL_TRANSACTIONS,
    COUNT(DISTINCT TXN_ID) AS UNIQUE_TXN_IDS,
    COUNT_IF(TXN_ID IS NULL OR TRIM(TXN_ID) = '') AS MISSING_TXN_IDS,
    COUNT_IF(MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '') AS MISSING_MEMBER_IDS,
    COUNT_IF(MILES_REDEEMED IS NULL OR MILES_REDEEMED < 0) AS INVALID_MILES,
    COUNT_IF(TXN_DATE IS NULL) AS MISSING_TXN_DATES
FROM SKYPOINTS_DB.STAGING.STG_REDEMPTIONS;



SELECT
    R.TXN_ID,
    R.MEMBER_ID,
    R.STATUS,
    CASE
        WHEN M.MEMBER_ID IS NULL
            THEN 'ORPHAN_MEMBER'
        WHEN R.STATUS NOT IN ('COMPLETED', 'PENDING', 'FAILED')
            OR R.STATUS IS NULL
            THEN 'INVALID_STATUS'
        ELSE 'VALID'
    END AS VALIDATION_STATUS
FROM SKYPOINTS_DB.STAGING.STG_REDEMPTIONS R
LEFT JOIN SKYPOINTS_DB.TARGET.MEMBER_CURRENT M
    ON R.MEMBER_ID = M.MEMBER_ID;
