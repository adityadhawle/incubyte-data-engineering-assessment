-- Pipe-delimited file format, internal stage, landing table, COPY INTO,
-- landing validation, RAW merge and latest MEMBER_CURRENT merge.
CREATE OR REPLACE FILE FORMAT SKYPOINTS_DB.RAW.MEMBER_PIPE_FORMAT
TYPE = CSV
FIELD_DELIMITER = '|'
SKIP_HEADER = 0
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
TRIM_SPACE = TRUE
EMPTY_FIELD_AS_NULL = TRUE
NULL_IF = ('NULL', 'null');

CREATE STAGE IF NOT EXISTS SKYPOINTS_DB.RAW.MEMBER_FILE_STAGE
FILE_FORMAT = SKYPOINTS_DB.RAW.MEMBER_PIPE_FORMAT;

SKYPOINTS_DB.RAW.MEMBER_FILE_STAGESKYPOINTS_DB.RAW.MEMBER_FILE_STAGESKYPOINTS_DB.RAW.MEMBER_FILE_STAGESKYPOINTS_DB.RAW.MEMBER_FILE_STAGESKYPOINTS_DB.RAW.MEMBER_FILE_STAGESKYPOINTS_DB.RAW.MEMBER_FILE_STAGE

LIST @SKYPOINTS_DB.RAW.MEMBER_FILE_STAGE;

CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.RAW.RAW_MEMBER_FILE_LANDING (
    FIELD_1  VARCHAR,
    FIELD_2  VARCHAR,
    FIELD_3  VARCHAR,
    FIELD_4  VARCHAR,
    FIELD_5  VARCHAR,
    FIELD_6  VARCHAR,
    FIELD_7  VARCHAR,
    FIELD_8  VARCHAR,
    FIELD_9  VARCHAR,
    FIELD_10 VARCHAR,
    FIELD_11 VARCHAR,
    FIELD_12 VARCHAR
);

COPY INTO SKYPOINTS_DB.RAW.RAW_MEMBER_FILE_LANDING
FROM @SKYPOINTS_DB.RAW.MEMBER_FILE_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'SKYPOINTS_DB.RAW.MEMBER_PIPE_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';

SELECT * 
FROM SKYPOINTS_DB.RAW.RAW_MEMBER_FILE_LANDING;

SELECT COUNT(*) AS EXISTING_RECORDS
FROM SKYPOINTS_DB.RAW.RAW_MEMBER_PROFILE;

SELECT
    L.FIELD_4 AS MEMBER_ID,
    COUNT(*) AS FILE_RECORD_COUNT
FROM SKYPOINTS_DB.RAW.RAW_MEMBER_FILE_LANDING L
WHERE L.FIELD_2 = 'D'
GROUP BY L.FIELD_4
HAVING COUNT(*) > 1;

SELECT
    L.FIELD_4 AS FILE_MEMBER_ID,
    L.FIELD_3 AS FILE_MEMBER_NAME,
    R.MEMBER_ID AS RAW_MEMBER_ID,
    R.MEMBER_NAME AS RAW_MEMBER_NAME,
    CASE
        WHEN R.MEMBER_ID IS NOT NULL THEN 'MATCHED'
        ELSE 'NOT FOUND'
    END AS VALIDATION_STATUS
FROM SKYPOINTS_DB.RAW.RAW_MEMBER_FILE_LANDING L
LEFT JOIN SKYPOINTS_DB.RAW.RAW_MEMBER_PROFILE R
    ON L.FIELD_4 = R.MEMBER_ID
WHERE L.FIELD_2 = 'D';

MERGE INTO SKYPOINTS_DB.RAW.RAW_MEMBER_PROFILE T
USING (
    SELECT
        FIELD_3 AS MEMBER_NAME,
        FIELD_4 AS MEMBER_ID,
        FIELD_5 AS ENROLLMENT_DATE,
        FIELD_6 AS LAST_FLIGHT_DATE,
        FIELD_7 AS TIER_CODE,
        FIELD_8 AS AGENT_NAME,
        FIELD_9 AS STATE,
        FIELD_10 AS COUNTRY,
        FIELD_11 AS DOB,
        FIELD_12 AS IS_ACTIVE
    FROM SKYPOINTS_DB.RAW.RAW_MEMBER_FILE_LANDING
    WHERE FIELD_2 = 'D'
) S
ON T.MEMBER_ID = S.MEMBER_ID

WHEN MATCHED AND (
    T.MEMBER_NAME IS DISTINCT FROM S.MEMBER_NAME OR
    T.ENROLLMENT_DATE IS DISTINCT FROM S.ENROLLMENT_DATE OR
    T.LAST_FLIGHT_DATE IS DISTINCT FROM S.LAST_FLIGHT_DATE OR
    T.TIER_CODE IS DISTINCT FROM S.TIER_CODE OR
    T.AGENT_NAME IS DISTINCT FROM S.AGENT_NAME OR
    T.STATE IS DISTINCT FROM S.STATE OR
    T.COUNTRY IS DISTINCT FROM S.COUNTRY OR
    T.DOB IS DISTINCT FROM S.DOB OR
    T.IS_ACTIVE IS DISTINCT FROM S.IS_ACTIVE
)
THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.LAST_FLIGHT_DATE = S.LAST_FLIGHT_DATE,
    T.TIER_CODE = S.TIER_CODE,
    T.AGENT_NAME = S.AGENT_NAME,
    T.STATE = S.STATE,
    T.COUNTRY = S.COUNTRY,
    T.DOB = S.DOB,
    T.IS_ACTIVE = S.IS_ACTIVE,
    T.SOURCE_FILE = 'member_profile_sample.txt',
    T.INGESTION_TIME = CURRENT_TIMESTAMP(),
    T.BATCH_ID = 'FILE_BATCH_001'

WHEN NOT MATCHED THEN INSERT (
    MEMBER_NAME, MEMBER_ID, ENROLLMENT_DATE,
    LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME,
    STATE, COUNTRY, DOB, IS_ACTIVE,
    SOURCE_FILE, INGESTION_TIME, BATCH_ID
)
VALUES (
    S.MEMBER_NAME, S.MEMBER_ID, S.ENROLLMENT_DATE,
    S.LAST_FLIGHT_DATE, S.TIER_CODE, S.AGENT_NAME,
    S.STATE, S.COUNTRY, S.DOB, S.IS_ACTIVE,
    'member_profile_sample.txt', CURRENT_TIMESTAMP(),
    'FILE_BATCH_001'
);

SELECT
    MEMBER_ID,
    MEMBER_NAME,
    COUNTRY,
    SOURCE_FILE,
    BATCH_ID
FROM SKYPOINTS_DB.RAW.RAW_MEMBER_PROFILE
ORDER BY MEMBER_ID;



DESC TABLE SKYPOINTS_DB.TARGET.MEMBER_CURRENT;



SELECT
    COUNT(*) AS TOTAL_MEMBERS,
    COUNT(DISTINCT MEMBER_ID) AS UNIQUE_MEMBERS,
    COUNT_IF(MEMBER_ID IS NULL) AS NULL_MEMBER_IDS
FROM SKYPOINTS_DB.TARGET.MEMBER_CURRENT;



