-- ============================================================
-- 7. REDEMPTION PIPELINE VALIDATION
-- ============================================================

SELECT
    COUNT(*) AS TOTAL_REDEMPTIONS,
    COUNT(DISTINCT TXN_ID) AS UNIQUE_TXN_IDS,
    COUNT_IF(TXN_ID IS NULL OR TRIM(TXN_ID) = '')
        AS MISSING_TXN_IDS,
    COUNT_IF(MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '')
        AS MISSING_MEMBER_IDS,
    COUNT_IF(TXN_DATE IS NULL)
        AS INVALID_TXN_DATES,
    COUNT_IF(MILES_REDEEMED IS NULL OR MILES_REDEEMED <= 0)
        AS INVALID_MILES,
    COUNT_IF(PARTNER IS NULL OR TRIM(PARTNER) = '')
        AS MISSING_PARTNERS,
    COUNT_IF(STATUS IS NULL OR TRIM(STATUS) = '')
        AS MISSING_STATUSES
FROM SKYPOINTS_DB.TARGET.FACT_REDEMPTIONS;

-- Duplicate composite transaction keys.
SELECT
    MEMBER_ID,
    TXN_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM SKYPOINTS_DB.TARGET.FACT_REDEMPTIONS
GROUP BY MEMBER_ID, TXN_ID
HAVING COUNT(*) > 1;

-- Orphan redemption records.
SELECT
    R.TXN_ID,
    R.MEMBER_ID
FROM SKYPOINTS_DB.TARGET.FACT_REDEMPTIONS R
LEFT JOIN SKYPOINTS_DB.TARGET.MEMBER_CURRENT M
    ON R.MEMBER_ID = M.MEMBER_ID
WHERE M.MEMBER_ID IS NULL;

-- Partner and transaction status summary.
SELECT
    PARTNER,
    STATUS,
    COUNT(*) AS TOTAL_TRANSACTIONS,
    SUM(MILES_REDEEMED) AS TOTAL_MILES_REDEEMED
FROM SKYPOINTS_DB.TARGET.FACT_REDEMPTIONS
GROUP BY PARTNER, STATUS
ORDER BY PARTNER, STATUS;

-- Redemption details with member information.
SELECT
    R.TXN_ID,
    R.MEMBER_ID,
    M.MEMBER_NAME,
    M.COUNTRY,
    R.TXN_DATE,
    R.PARTNER,
    R.MILES_REDEEMED,
    R.STATUS
FROM SKYPOINTS_DB.TARGET.FACT_REDEMPTIONS R
LEFT JOIN SKYPOINTS_DB.TARGET.MEMBER_CURRENT M
    ON R.MEMBER_ID = M.MEMBER_ID
ORDER BY R.TXN_DATE;

