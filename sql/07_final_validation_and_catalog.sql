-- ============================================================
-- 12. QUERY EXECUTION HISTORY
-- ============================================================

SELECT
    START_TIME,
    QUERY_TYPE,
    EXECUTION_STATUS,
    QUERY_TEXT
FROM TABLE(
    SKYPOINTS_DB.INFORMATION_SCHEMA.QUERY_HISTORY(
        END_TIME_RANGE_START => DATEADD('DAY', -7, CURRENT_TIMESTAMP()),
        END_TIME_RANGE_END => CURRENT_TIMESTAMP(),
        RESULT_LIMIT => 1000
    )
)
WHERE
       QUERY_TEXT ILIKE '%STG_MEMBER_PROFILE%'
    OR QUERY_TEXT ILIKE '%MEMBER_CURRENT%'
    OR QUERY_TEXT ILIKE '%RAW_MEMBER_PROFILE%'
ORDER BY START_TIME DESC;
