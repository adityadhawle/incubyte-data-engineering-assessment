-- ============================================================
-- 5. CENTRAL MEMBER TABLE VALIDATION
-- ============================================================

SELECT
    COUNT(*) AS TOTAL_MEMBERS,
    COUNT(DISTINCT MEMBER_ID) AS UNIQUE_MEMBER_IDS,
    COUNT_IF(MEMBER_ID IS NULL OR TRIM(MEMBER_ID) = '')
        AS MISSING_MEMBER_IDS,
    COUNT_IF(MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = '')
        AS MISSING_MEMBER_NAMES,
    COUNT_IF(COUNTRY IS NULL OR TRIM(COUNTRY) = '')
        AS MISSING_COUNTRIES,
    COUNT_IF(ENROLLMENT_DATE IS NULL)
        AS MISSING_ENROLLMENT_DATES,
    COUNT_IF(LAST_FLIGHT_DATE IS NULL)
        AS MISSING_FLIGHT_DATES,
    COUNT_IF(STALE_MEMBER = TRUE)
        AS STALE_MEMBERS,
    COUNT_IF(STALE_MEMBER IS NULL)
        AS UNKNOWN_STALE_STATUS
FROM SKYPOINTS_DB.TARGET.MEMBER_CURRENT;

-- Duplicate member IDs.
SELECT
    MEMBER_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM SKYPOINTS_DB.TARGET.MEMBER_CURRENT
GROUP BY MEMBER_ID
HAVING COUNT(*) > 1;

-- Central member distribution by country.
SELECT
    COUNTRY,
    COUNT(*) AS MEMBER_COUNT,
    COUNT(DISTINCT MEMBER_ID) AS UNIQUE_MEMBERS
FROM SKYPOINTS_DB.TARGET.MEMBER_CURRENT
GROUP BY COUNTRY
ORDER BY COUNTRY;

-- Latest member record for migration verification.
SELECT
    MEMBER_ID,
    MEMBER_NAME,
    COUNTRY,
    BATCH_ID,
    INGESTION_TIME
FROM SKYPOINTS_DB.TARGET.MEMBER_CURRENT
WHERE MEMBER_ID = '223458';

