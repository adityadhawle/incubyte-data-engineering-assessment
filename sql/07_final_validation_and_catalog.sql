    TABLE_SCHEMA AS SCHEMA_NAME,
    TABLE_NAME AS OBJECT_NAME,
    TABLE_TYPE AS OBJECT_TYPE
FROM SKYPOINTS_DB.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA IN ('RAW', 'STAGING', 'TARGET', 'AUDIT')

UNION ALL

SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    'VIEW' AS OBJECT_TYPE
FROM SKYPOINTS_DB.INFORMATION_SCHEMA.VIEWS
WHERE TABLE_SCHEMA IN ('RAW', 'STAGING', 'TARGET', 'AUDIT')

UNION ALL

SELECT
    STAGE_SCHEMA,
    STAGE_NAME,
    'STAGE'
FROM SKYPOINTS_DB.INFORMATION_SCHEMA.STAGES
WHERE STAGE_SCHEMA IN ('RAW', 'STAGING', 'TARGET', 'AUDIT')

UNION ALL

SELECT
    FILE_FORMAT_SCHEMA,
    FILE_FORMAT_NAME,
    'FILE FORMAT'
FROM SKYPOINTS_DB.INFORMATION_SCHEMA.FILE_FORMATS
WHERE FILE_FORMAT_SCHEMA IN ('RAW', 'STAGING', 'TARGET', 'AUDIT')

ORDER BY SCHEMA_NAME, OBJECT_TYPE, OBJECT_NAME;

-- ============================================================
-- 3. COLUMN-LEVEL CATALOG
-- ============================================================

