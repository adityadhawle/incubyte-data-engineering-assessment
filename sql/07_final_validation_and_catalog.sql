    FROM SKYPOINTS_DB.STAGING.STG_MEMBER_PROFILE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY MEMBER_ID
        ORDER BY INGESTION_TIME DESC, BATCH_ID DESC
    ) = 1
) S
ON T.MEMBER_ID = S.MEMBER_ID

WHEN MATCHED AND (
       T.MEMBER_NAME IS DISTINCT FROM S.MEMBER_NAME
    OR T.ENROLLMENT_DATE IS DISTINCT FROM S.ENROLLMENT_DATE
    OR T.LAST_FLIGHT_DATE IS DISTINCT FROM S.LAST_FLIGHT_DATE
    OR T.TIER_CODE IS DISTINCT FROM S.TIER_CODE
    OR T.AGENT_NAME IS DISTINCT FROM S.AGENT_NAME
    OR T.STATE IS DISTINCT FROM S.STATE
    OR T.COUNTRY IS DISTINCT FROM S.COUNTRY
    OR T.DOB IS DISTINCT FROM S.DOB
    OR T.AGE IS DISTINCT FROM S.AGE
    OR T.IS_ACTIVE IS DISTINCT FROM S.IS_ACTIVE
    OR T.STALE_MEMBER IS DISTINCT FROM S.STALE_MEMBER
    OR T.SOURCE_FILE IS DISTINCT FROM S.SOURCE_FILE
    OR T.INGESTION_TIME IS DISTINCT FROM S.INGESTION_TIME
    OR T.BATCH_ID IS DISTINCT FROM S.BATCH_ID
    OR (S.POST_CODE IS NOT NULL
        AND T.POST_CODE IS DISTINCT FROM S.POST_CODE)
)
THEN UPDATE SET
    T.MEMBER_NAME = S.MEMBER_NAME,
    T.ENROLLMENT_DATE = S.ENROLLMENT_DATE,
    T.LAST_FLIGHT_DATE = S.LAST_FLIGHT_DATE,
    T.TIER_CODE = S.TIER_CODE,
    T.AGENT_NAME = S.AGENT_NAME,
    T.STATE = S.STATE,
    T.COUNTRY = S.COUNTRY,
    T.DOB = S.DOB,
    T.AGE = S.AGE,
    T.IS_ACTIVE = S.IS_ACTIVE,
    T.STALE_MEMBER = S.STALE_MEMBER,
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.INGESTION_TIME = S.INGESTION_TIME,
    T.BATCH_ID = S.BATCH_ID,
    T.POST_CODE = COALESCE(S.POST_CODE, T.POST_CODE)

WHEN NOT MATCHED THEN INSERT (
    MEMBER_NAME, MEMBER_ID, ENROLLMENT_DATE,
    LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME,
    STATE, COUNTRY, DOB, AGE, IS_ACTIVE,
    STALE_MEMBER, SOURCE_FILE, INGESTION_TIME,
    BATCH_ID, POST_CODE
)
VALUES (
    S.MEMBER_NAME, S.MEMBER_ID, S.ENROLLMENT_DATE,
    S.LAST_FLIGHT_DATE, S.TIER_CODE, S.AGENT_NAME,
    S.STATE, S.COUNTRY, S.DOB, S.AGE, S.IS_ACTIVE,
    S.STALE_MEMBER, S.SOURCE_FILE, S.INGESTION_TIME,
    S.BATCH_ID, S.POST_CODE
);

