CREATE TABLE IF NOT EXISTS SKYPOINTS_DB.STAGING.STG_REDEMPTIONS (
    MEMBER_ID       VARCHAR(18),
    FEED_DATE       DATE,
    TXN_ID          VARCHAR(50),
    TXN_DATE        DATE,
    PARTNER         VARCHAR(100),
    MILES_REDEEMED  NUMBER(12,0),
    STATUS          VARCHAR(30),
    SOURCE_FILE     VARCHAR(500),
