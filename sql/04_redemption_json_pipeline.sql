MERGE INTO SKYPOINTS_DB.TARGET.FACT_REDEMPTIONS T
USING (
    SELECT *
    FROM SKYPOINTS_DB.STAGING.STG_REDEMPTIONS
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY TXN_ID
        ORDER BY INGESTION_TIME DESC, BATCH_ID DESC
    ) = 1
) S
ON T.TXN_ID = S.TXN_ID

WHEN MATCHED THEN UPDATE SET
    T.MEMBER_ID = S.MEMBER_ID,
    T.FEED_DATE = S.FEED_DATE,
    T.TXN_DATE = S.TXN_DATE,
    T.PARTNER = S.PARTNER,
    T.MILES_REDEEMED = S.MILES_REDEEMED,
    T.STATUS = S.STATUS,
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.INGESTION_TIME = S.INGESTION_TIME,
    T.BATCH_ID = S.BATCH_ID

WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID, TXN_ID, FEED_DATE, TXN_DATE,
    PARTNER, MILES_REDEEMED, STATUS,
    SOURCE_FILE, INGESTION_TIME, BATCH_ID
)
VALUES (
    S.MEMBER_ID, S.TXN_ID, S.FEED_DATE, S.TXN_DATE,
    S.PARTNER, S.MILES_REDEEMED, S.STATUS,
    S.SOURCE_FILE, S.INGESTION_TIME, S.BATCH_ID
);
SELECT
    TXN_ID,
    COUNT(*) AS RECORD_COUNT
FROM SKYPOINTS_DB.TARGET.FACT_REDEMPTIONS
GROUP BY TXN_ID
HAVING COUNT(*) > 1;



MERGE INTO SKYPOINTS_DB.TARGET.FACT_REDEMPTIONS T
USING (
    SELECT
        MEMBER_ID,
        FEED_DATE,
        TXN_ID,
        TXN_DATE,
        PARTNER,
        MILES_REDEEMED,
        STATUS,
        SOURCE_FILE,
        INGESTION_TIME,
        BATCH_ID
    FROM SKYPOINTS_DB.STAGING.STG_REDEMPTIONS
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY TXN_ID
        ORDER BY INGESTION_TIME DESC, BATCH_ID DESC
    ) = 1
) S
ON T.TXN_ID = S.TXN_ID

WHEN MATCHED AND (
       T.MEMBER_ID IS DISTINCT FROM S.MEMBER_ID
    OR T.FEED_DATE IS DISTINCT FROM S.FEED_DATE
    OR T.TXN_DATE IS DISTINCT FROM S.TXN_DATE
    OR T.PARTNER IS DISTINCT FROM S.PARTNER
    OR T.MILES_REDEEMED IS DISTINCT FROM S.MILES_REDEEMED
    OR T.STATUS IS DISTINCT FROM S.STATUS
    OR T.SOURCE_FILE IS DISTINCT FROM S.SOURCE_FILE
    OR T.INGESTION_TIME IS DISTINCT FROM S.INGESTION_TIME
    OR T.BATCH_ID IS DISTINCT FROM S.BATCH_ID
)
THEN UPDATE SET
    T.MEMBER_ID = S.MEMBER_ID,
    T.FEED_DATE = S.FEED_DATE,
    T.TXN_DATE = S.TXN_DATE,
    T.PARTNER = S.PARTNER,
    T.MILES_REDEEMED = S.MILES_REDEEMED,
    T.STATUS = S.STATUS,
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.INGESTION_TIME = S.INGESTION_TIME,
    T.BATCH_ID = S.BATCH_ID

WHEN NOT MATCHED THEN INSERT (
    MEMBER_ID,
    FEED_DATE,
    TXN_ID,
    TXN_DATE,
    PARTNER,
    MILES_REDEEMED,
    STATUS,
    SOURCE_FILE,
    INGESTION_TIME,
    BATCH_ID
)
VALUES (
    S.MEMBER_ID,
    S.FEED_DATE,
    S.TXN_ID,
    S.TXN_DATE,
    S.PARTNER,
    S.MILES_REDEEMED,
    S.STATUS,
    S.SOURCE_FILE,
    S.INGESTION_TIME,
    S.BATCH_ID
);
